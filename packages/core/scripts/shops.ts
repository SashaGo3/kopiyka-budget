/**
 * Writes apps/mobile/native/KPShops.swift from src/shops.ts, so the notification automation (which
 * runs with the app closed) knows the same shops the app does.
 *
 *   bun run scripts/shops.ts
 *
 * test/shops.test.ts fails when the Swift file is older than the list.
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { shopTerms } from "../src/shops";

export function shopsSwift(): string {
  const rows = shopTerms().map(({ term, type }) => `    (${JSON.stringify(term)}, ${JSON.stringify(type)}),`).join("\n");
  return `// Generated by packages/core/scripts/shops.ts from packages/core/src/shops.ts — do not edit.
import Foundation

/// Shops everybody knows and the category type each one is (core \`shopType\`, DATA.md rule 21).
enum KPShops {
  /// Normalised terms, longest first, so "uber eats" is tried before "uber".
  static let terms: [(term: String, type: String)] = [
${rows}
  ]

  /// Mirrors core \`normalizeName\`: lower case, ł → l, accents off, anything but a-z, 0-9 and
  /// Cyrillic a space, spaces collapsed. The two must agree or a shop matches on one side only.
  static func normalize(_ s: String) -> String {
    let lowered = s.lowercased().replacingOccurrences(of: "ł", with: "l")
    var out = ""
    var space = false
    for u in lowered.decomposedStringWithCompatibilityMapping.unicodeScalars {
      if (0x300...0x36F).contains(u.value) { continue }
      let keep = (u.value >= 0x61 && u.value <= 0x7A) || (u.value >= 0x30 && u.value <= 0x39) || (0x400...0x4FF).contains(u.value)
      if keep { if space && !out.isEmpty { out.append(" ") }; space = false; out.unicodeScalars.append(u) } else { space = true }
    }
    return out
  }

  /// The type a shop's name says it is, or nil: whole words, longest term first, each name in turn.
  static func type(_ names: String?...) -> String? {
    for raw in names {
      guard let raw else { continue }
      let n = " \\(normalize(raw)) "
      if n.count < 4 { continue }
      for t in terms where n.contains(" \\(t.term) ") { return t.type }
    }
    return nil
  }
}
`;
}

if (import.meta.main) {
  const out = join(import.meta.dir, "../../../apps/mobile/native/KPShops.swift");
  writeFileSync(out, shopsSwift());
  console.log(`wrote ${out}`);
}
